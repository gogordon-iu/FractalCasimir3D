"""
Dynamic Micro-Probe Profiler & Slurm Dispatch Generator for IUB Big Red 200.
Empirically times candidate execution via a localized probe run, estimates local vs.
cluster runtimes, and prepares cluster submission scripts compliant with IUB Big Red 200 policies.
"""

import os
import sys
import time
import json
import argparse
import subprocess
import shutil
from pathlib import Path
from typing import Dict, Any

BIGRED200_CONFIG = {
    "default_account": "r01540",
    "gpu_partition": "gpu",
    "cpu_partition": "general",
    "gpu_speedup_factor": 12.0,   # Baseline NVIDIA A100-SXM4-40GB vs local machine
    "cpu_speedup_factor": 3.5,    # AMD EPYC 7742 vs local core
    "local_cutoff_minutes": 10.0, # Executions > 10 min routed to Big Red 200
}


def run_empirical_probe(
    entry_script: str,
    probe_steps: int = 5,
    extra_args: str = "",
) -> Dict[str, Any]:
    """
    Executes a real micro-run locally via subprocess, measuring empirical step latency.
    """
    cmd = [sys.executable, entry_script, "--max-steps", str(probe_steps)]
    if extra_args.strip():
        cmd.extend(extra_args.strip().split())

    print(f"[HPC-GATE] Running empirical micro-probe: {' '.join(cmd)}")
    start_time = time.perf_counter()
    result = subprocess.run(cmd, capture_output=True, text=True)
    total_elapsed = time.perf_counter() - start_time

    if result.returncode != 0:
        return {
            "status": "PROBE_FAILED",
            "returncode": result.returncode,
            "stderr": result.stderr,
            "stdout": result.stdout,
        }

    sec_per_step = max(total_elapsed / max(probe_steps, 1), 0.001)

    return {
        "status": "PASS",
        "probe_elapsed_sec": total_elapsed,
        "sec_per_step": sec_per_step,
        "stdout_tail": result.stdout.strip().split("\n")[-3:] if result.stdout else [],
    }


def evaluate_workload(
    probe_result: Dict[str, Any],
    total_planned_steps: int,
    gpu_required: bool = True,
    cutoff_minutes: float = BIGRED200_CONFIG["local_cutoff_minutes"],
) -> Dict[str, Any]:
    """
    Computes projected local runtime vs Big Red 200 runtime from empirical probe latency.
    """
    if probe_result.get("status") != "PASS":
        return {"status": "ERROR", "message": "Cannot evaluate failed probe"}

    sec_per_step = probe_result["sec_per_step"]
    est_total_sec_local = sec_per_step * total_planned_steps
    est_total_min_local = est_total_sec_local / 60.0

    speedup = (
        BIGRED200_CONFIG["gpu_speedup_factor"]
        if gpu_required
        else BIGRED200_CONFIG["cpu_speedup_factor"]
    )
    est_total_sec_bigred = max(est_total_sec_local / speedup, 15.0)
    est_total_min_bigred = est_total_sec_bigred / 60.0

    route_to_cluster = est_total_min_local > cutoff_minutes

    return {
        "status": "SUCCESS",
        "sec_per_step_local": round(sec_per_step, 4),
        "est_total_min_local": round(est_total_min_local, 2),
        "est_total_min_bigred200": round(est_total_min_bigred, 2),
        "target_environment": "BIGRED200" if route_to_cluster else "LOCAL",
        "requires_gpu": gpu_required,
    }


def generate_slurm_script(
    job_name: str,
    entry_script: str,
    full_args: str,
    est_minutes_bigred: float,
    account: str = BIGRED200_CONFIG["default_account"],
    gpus: int = 1,
    cpus_per_task: int = 8,
    memory_gb: int = 64,
    output_path: str = "submit_bigred200.slurm",
) -> str:
    """
    Generates an IUB Big Red 200 Slurm submission script wrapping the exact execution command
    with verified account directives, partition settings, and offline node isolation flags.
    """
    buffer_minutes = int(est_minutes_bigred * 1.5) + 10
    hours = buffer_minutes // 60
    minutes = buffer_minutes % 60
    walltime_str = f"{hours:02d}:{minutes:02d}:00"

    partition = BIGRED200_CONFIG["gpu_partition"] if gpus > 0 else BIGRED200_CONFIG["cpu_partition"]
    gpu_directive = f"#SBATCH --gpus={gpus}" if gpus > 0 else "# No GPU requested"

    slurm_content = f"""#!/bin/bash
#SBATCH -J {job_name}
#SBATCH -A {account}
#SBATCH -p {partition}
#SBATCH -o logs/%x_%j.out
#SBATCH -e logs/%x_%j.err
#SBATCH --nodes=1
#SBATCH --ntasks-per-node=1
#SBATCH --cpus-per-task={cpus_per_task}
#SBATCH --mem={memory_gb}G
#SBATCH --time={walltime_str}
{gpu_directive}

# ==============================================================================
# IUB Big Red 200 Cray EX Execution Harness
# Generated by Antigravity hpc-workload-gate
# Account: {account} | Partition: {partition}
# ==============================================================================

# Big Red 200 Compute Nodes have NO internet access:
# Set offline cache directories and disable WAN phone-home attempts
export HF_HUB_OFFLINE=1
export TRANSFORMERS_OFFLINE=1
export HF_DATASETS_OFFLINE=1
export WANDB_MODE=offline
export TORCH_HOME="$SCRATCH/torch_cache"

module purge
module load python/gpu/3.10.10

# Source project venv if present
if [ -d "$HOME/venvs/research" ]; then
    source "$HOME/venvs/research/bin/activate"
fi

mkdir -p results figures logs

echo "=== [Big Red 200 Job Started: $(date)] ==="
echo "Host: $(hostname)"
echo "CUDA_VISIBLE_DEVICES: $CUDA_VISIBLE_DEVICES"

# Execute unmodified Python script with full production parameters
python {entry_script} {full_args}
EXIT_CODE=$?

echo "=== [Execution Finished with exit code: $EXIT_CODE at $(date)] ==="

# Enforce Provenance Contract
if [ -f "results/provenance_metrics.json" ]; then
    echo "[PROVENANCE CONFIRMED] results/provenance_metrics.json verified."
else
    echo "[ERROR: RUN_DATA_MISSING] results/provenance_metrics.json was not generated!"
    exit 1
fi

exit $EXIT_CODE
"""
    out_file = Path(output_path)
    out_file.parent.mkdir(parents=True, exist_ok=True)
    with open(out_file, "w", encoding="utf-8", newline="\n") as f:
        f.write(slurm_content)

    sandbox_checker = shutil.which("br200_sandbox")
    if sandbox_checker:
        subprocess.run([sandbox_checker, str(out_file)], check=True)

    return str(out_file)


def init_workspace(target_dir: str = "utils") -> str:
    """Scaffolds hpc_gate.py into the specified target directory of the active project."""
    target_path = Path(target_dir) / "hpc_gate.py"
    target_path.parent.mkdir(parents=True, exist_ok=True)
    this_file = Path(__file__).resolve()
    shutil.copy2(this_file, target_path)
    print(f"[HPC-GATE] Installed local copy to {target_path}")
    return str(target_path)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="IUB Big Red 200 Workload Gate & Profiler")
    parser.add_argument("--entry-script", help="Path to Python script to probe")
    parser.add_argument("--job-name", default="experiment_run")
    parser.add_argument("--probe-steps", type=int, default=5, help="Number of micro-probe steps")
    parser.add_argument("--planned-steps", type=int, default=1000, help="Total planned steps for full experiment")
    parser.add_argument("--full-args", default="", help="Command-line arguments for full run")
    parser.add_argument("--account", default=BIGRED200_CONFIG["default_account"], help="Slurm allocation account")
    parser.add_argument("--no-gpu", action="store_true", help="Set if workload is pure CPU")
    parser.add_argument("--init", action="store_true", help="Scaffold hpc_gate.py into utils/")
    args = parser.parse_args()

    if args.init:
        init_workspace()
        sys.exit(0)

    if not args.entry_script:
        print("[HPC-GATE] Missing --entry-script. Run with --help for usage.")
        sys.exit(1)

    probe = run_empirical_probe(args.entry_script, probe_steps=args.probe_steps)
    if probe.get("status") != "PASS":
        print(f"[HPC-GATE ERROR] Probe execution failed:\n{probe.get('stderr')}")
        sys.exit(1)

    eval_result = evaluate_workload(
        probe,
        total_planned_steps=args.planned_steps,
        gpu_required=not args.no_gpu,
    )
    print(f"\n[HPC-GATE PROFILE RESULT]\n{json.dumps(eval_result, indent=2)}")

    if eval_result["target_environment"] == "BIGRED200":
        slurm_path = generate_slurm_script(
            args.job_name,
            args.entry_script,
            args.full_args,
            eval_result["est_total_min_bigred200"],
            account=args.account,
            gpus=0 if args.no_gpu else 1,
        )
        print(f"\n[HPC-GATE] Job routes to Big Red 200. Slurm file created: {slurm_path}")
    else:
        print("\n[HPC-GATE] Projected runtime <= 10 min. Safe for direct local execution.")
